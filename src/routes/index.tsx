import { createFileRoute, Link } from "@tanstack/react-router";
import { useSuspenseQuery } from "@tanstack/react-query";
import { ArrowRight, Building2, Globe2, Leaf, ShieldCheck } from "lucide-react";
import { useState } from "react";

import { allInstrumentsQuery } from "@/lib/queries";
import { useI18n } from "@/i18n";
import { formatMoney, formatPercent, localizedName, unique } from "@/lib/format";
import { MarketExplorer, StatusBadge, defaultSearch, type MarketSearch } from "@/components/market/MarketExplorer";
import { Button } from "@/components/ui/button";
import { abs, byCountry, byStructure, datasetLd, faqPage, ldScript } from "@/lib/seo";


export const Route = createFileRoute("/")({
  head: () => ({
    meta: [
      { title: "Sukuk Market — Global Sukuk Screener" },
      {
        name: "description",
        content:
          "Screen sovereign, corporate and green sukuk across Malaysia, Saudi Arabia, the UAE, Indonesia, Qatar, Bahrain, Kuwait, Türkiye, Pakistan and Oman.",
      },
      { property: "og:title", content: "Sukuk Market — Global Sukuk Screener" },
      {
        property: "og:description",
        content: "Filter every major sukuk issue by country, structure, yield, rating and ESG — free to browse.",
      },
      { property: "og:type", content: "website" },
      { property: "og:url", content: abs("/") },
      { name: "twitter:card", content: "summary_large_image" },
    ],
    links: [{ rel: "canonical", href: abs("/") }],
    scripts: [
      ldScript(
        datasetLd({
          name: "Global sukuk screener dataset",
          description:
            "Reference data on sukuk worldwide: issuer, structure, currency, profit rate, yield to maturity, maturity, ratings, Shariah certification and ESG status.",
          path: "/",
        }),
      ),
      ldScript(
        faqPage([
          {
            q: "What is a sukuk?",
            a: "A sukuk is a Shariah-compliant investment certificate representing ownership in an asset, project or business activity. Holders receive distributions generated by that asset rather than interest.",
          },
          {
            q: "Where can I compare sukuk yields?",
            a: "Sukuk Market's free screener ranks sukuk by yield to maturity, rating, structure, currency and maturity across every major sukuk market.",
          },
          {
            q: "Does Sukuk Market sell sukuk?",
            a: "No. Sukuk Market is a screener and reference data service. Enquiries are routed to licensed partner desks in the relevant jurisdiction.",
          },
        ]),
      ),
    ],
  }),

  loader: ({ context }) => {
    context.queryClient.ensureQueryData(allInstrumentsQuery());
  },
  component: Home,
});

function Home() {
  const { t, lang, locale } = useI18n();
  const { data: rows } = useSuspenseQuery(allInstrumentsQuery());
  const [search, setSearch] = useState<MarketSearch>(defaultSearch);


  const sukuk = rows;
  const open = rows.filter((r) => r.status === "open");
  const countries = unique(rows.map((r) => r.issuer.country));
  const yields = rows.map((r) => r.yield_to_maturity).filter((v): v is number => v != null);
  const avgYield = yields.length ? yields.reduce((a, b) => a + b, 0) / yields.length : null;
  const structures = unique(sukuk.map((r) => r.structure ?? "")).slice(0, 8);
  const featured = rows.filter((r) => r.featured).slice(0, 6);

  return (
    <div>
      <section className="geo-pattern border-b border-border bg-surface">
        <div className="mx-auto max-w-7xl px-4 py-16 sm:py-24">
          <p className="text-xs font-semibold uppercase tracking-[0.24em] text-primary">{t("home.eyebrow")}</p>
          <h1 className="mt-4 max-w-3xl text-4xl font-bold leading-tight sm:text-6xl">{t("home.title")}</h1>
          <p className="mt-5 max-w-2xl text-base text-muted-foreground sm:text-lg">{t("home.subtitle")}</p>
          <div className="mt-8 flex flex-wrap gap-3">
            <Button asChild size="lg">
              <Link to="/market">
                {t("home.cta.browse")} <ArrowRight className="ms-2 h-4 w-4 rtl:rotate-180" />
              </Link>
            </Button>
            <Button asChild size="lg" variant="outline">
              <Link to="/learn">{t("home.cta.learn")}</Link>
            </Button>
          </div>

          <dl className="mt-14 grid grid-cols-2 gap-px overflow-hidden rounded-lg border border-border bg-border lg:grid-cols-4">
            <Stat icon={<Building2 className="h-4 w-4" />} label={t("home.stat.listings")} value={String(rows.length)} />
            <Stat icon={<Globe2 className="h-4 w-4" />} label={t("home.stat.countries")} value={String(countries.length)} />
            <Stat icon={<ShieldCheck className="h-4 w-4" />} label={t("home.stat.open")} value={String(open.length)} />
            <Stat icon={<Leaf className="h-4 w-4" />} label={t("home.stat.avgYield")} value={formatPercent(avgYield, locale)} />
          </dl>
        </div>
      </section>

      <section className="mx-auto max-w-7xl px-4 py-14">
        <div className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <h2 className="text-2xl font-bold">{t("home.featured")}</h2>
            <p className="mt-1 text-sm text-muted-foreground">{t("home.featured.sub")}</p>
          </div>
          <Link to="/market" className="text-sm font-medium text-primary hover:underline">
            {t("home.viewAll")}
          </Link>
        </div>

        <div className="mt-6 grid gap-4 md:grid-cols-2 lg:grid-cols-3">
          {featured.map((row) => (
            <Link
              key={row.id}
              to="/instrument/$slug"
              params={{ slug: row.slug }}
              className="group rounded-lg border border-border bg-card p-5 transition-colors hover:border-primary"
            >
              <div className="flex items-start justify-between gap-3">
                <div className="min-w-0">
                  <p className="truncate font-semibold group-hover:text-primary">{localizedName(row, lang)}</p>
                  <p className="truncate text-xs text-muted-foreground">{localizedName(row.issuer, lang)}</p>
                </div>
                <StatusBadge status={row.status} />
              </div>
              <div className="mt-5 grid grid-cols-3 gap-3 text-sm">
                <div>
                  <p className="text-[11px] uppercase tracking-wide text-muted-foreground">{t("col.yield")}</p>
                  <p className="tnum font-semibold">{formatPercent(row.yield_to_maturity, locale)}</p>
                </div>
                <div>
                  <p className="text-[11px] uppercase tracking-wide text-muted-foreground">{t("col.rate")}</p>
                  <p className="tnum font-semibold">{formatPercent(row.profit_rate, locale)}</p>
                </div>
                <div className="min-w-0">
                  <p className="text-[11px] uppercase tracking-wide text-muted-foreground">{t("col.size")}</p>
                  <p className="tnum truncate font-semibold">{formatMoney(row.size_amount, row.currency, locale)}</p>
                </div>
              </div>
            </Link>
          ))}
        </div>
      </section>

      <section className="border-t border-border">
        <div className="mx-auto max-w-7xl px-4 pt-14">
          <h2 className="text-2xl font-bold">{t("screener.title")}</h2>
          <p className="mt-1 text-sm text-muted-foreground">{t("screener.sub")}</p>
        </div>
        <MarketExplorer rows={rows} search={search} onChange={(patch) => setSearch((p) => ({ ...p, ...patch }))} />
      </section>



      <section className="border-t border-border bg-surface">
        <div className="mx-auto max-w-7xl px-4 py-14">
          <h2 className="text-2xl font-bold">{t("home.structures")}</h2>
          <div className="mt-6 flex flex-wrap gap-2">
            {structures.map((s) => (
              <Link
                key={s}
                to="/market"
                search={{ structure: s }}
                className="rounded-full border border-border bg-card px-4 py-2 text-sm font-medium transition-colors hover:border-primary hover:text-primary"
              >
                {s}
              </Link>
            ))}
          </div>
        </div>
      </section>

      <section className="mx-auto max-w-7xl px-4 py-14">
        <h2 className="text-2xl font-bold">Explore by market</h2>
        <div className="mt-5 flex flex-wrap gap-2">
          {byCountry(rows).map((c) => (
            <Link
              key={c.slug}
              to="/country/$slug"
              params={{ slug: c.slug }}
              className="rounded-full border border-border bg-card px-4 py-2 text-sm font-medium transition-colors hover:border-primary hover:text-primary"
            >
              {c.country} ({c.rows.length})
            </Link>
          ))}
        </div>

        <h2 className="mt-10 text-2xl font-bold">Explore by structure</h2>
        <div className="mt-5 flex flex-wrap gap-2">
          {byStructure(rows).map((s) => (
            <Link
              key={s.slug}
              to="/structure/$slug"
              params={{ slug: s.slug }}
              className="rounded-full border border-border bg-card px-4 py-2 text-sm font-medium transition-colors hover:border-primary hover:text-primary"
            >
              {s.structure} ({s.rows.length})
            </Link>
          ))}
        </div>

        <h2 className="mt-10 text-2xl font-bold">Common questions</h2>
        <div className="mt-5 flex flex-wrap gap-3 text-sm">
          <Link to="/answers" className="font-medium text-primary hover:underline">
            All sukuk answers
          </Link>
          <Link to="/data" className="font-medium text-primary hover:underline">
            Open sukuk data (JSON / CSV)
          </Link>
        </div>
      </section>
    </div>

  );
}

function Stat({ icon, label, value }: { icon: React.ReactNode; label: string; value: string }) {
  return (
    <div className="bg-card p-5">
      <dt className="flex items-center gap-2 text-xs uppercase tracking-wide text-muted-foreground">
        {icon}
        {label}
      </dt>
      <dd className="tnum mt-2 text-2xl font-bold">{value}</dd>
    </div>
  );
}
